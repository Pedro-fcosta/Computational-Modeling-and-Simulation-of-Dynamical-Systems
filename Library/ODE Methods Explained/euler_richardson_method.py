# Euler-Richardson method for solving the second-order ODE of a simple harmonic oscillator
# 
# 
#
#
#
#
# Initial Value Problem (IVP)
# Differential equation in differential form:
# m*x'' + kx = 0
#
# Equivalent form:
# x'' = -(k/m) * x
#
# Initial conditions:
# x(0) = 1
# v(0) = x'(0) = 0
#
# Parameters:
# m = 1
# k = 4